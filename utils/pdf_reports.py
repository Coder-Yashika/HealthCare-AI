from io import BytesIO
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Table,
    TableStyle
)


def generate_medical_report(
    disease_name,
    patient_details,
    prediction,
    confidence,
    recommendations
):
    """
    Returns PDF bytes for Streamlit download button.
    """

    buffer = BytesIO()

    doc = SimpleDocTemplate(buffer)

    styles = getSampleStyleSheet()

    story = []

    # ===========================
    # Title
    # ===========================

    story.append(Paragraph("<b><font size=18>AI Disease Prediction Report</font></b>", styles["Title"]))

    story.append(Spacer(1, 20))

    # ===========================
    # Disease
    # ===========================

    story.append(Paragraph(f"<b>Disease:</b> {disease_name}", styles["Heading2"]))
    story.append(Paragraph(f"<b>Prediction:</b> {prediction}", styles["Normal"]))
    story.append(Paragraph(f"<b>Confidence:</b> {confidence:.2f}%", styles["Normal"]))

    story.append(Spacer(1, 20))

    # ===========================
    # Patient Information
    # ===========================

    story.append(Paragraph("<b>Patient Summary</b>", styles["Heading2"]))

    data = [["Parameter", "Value"]]

    for key, value in patient_details.items():
        data.append([key, str(value)])

    table = Table(data)

    table.setStyle(
        TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.darkblue),
            ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),

            ("GRID", (0, 0), (-1, -1), 1, colors.grey),

            ("BACKGROUND", (0, 1), (-1, -1), colors.beige),

            ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
        ])
    )

    story.append(table)

    story.append(Spacer(1, 20))

    # ===========================
    # Recommendations
    # ===========================

    story.append(Paragraph("<b>Recommendations</b>", styles["Heading2"]))

    for rec in recommendations:
        story.append(Paragraph(f"• {rec}", styles["Normal"]))

    story.append(Spacer(1, 20))

    # ===========================
    # Disclaimer
    # ===========================

    disclaimer = """
    <b>Medical Disclaimer</b><br/><br/>

    This report is generated using Machine Learning models.

    It is intended for educational and screening purposes only.

    It should NOT replace professional medical diagnosis.

    Please consult a qualified healthcare professional.
    """

    story.append(Paragraph(disclaimer, styles["Normal"]))

    story.append(Spacer(1, 30))

    story.append(
        Paragraph(
            "<b>Generated by AI Disease Prediction System</b>",
            styles["Heading3"]
        )
    )

    doc.build(story)

    pdf = buffer.getvalue()

    buffer.close()

    return pdf